library(TALLBMDeconv)
# Entirely synthetic counts; no patient observations or atlas cells.
x<-matrix(c(20,4,8,3,5,1,18,5,9,3,4,2,2,18,1,16,2,8,3,17,2,15,3,9,19,4,8,2,6,1,2,19,1,15,2,9),nrow=6)
colnames(x)<-paste0("cell",1:6);rownames(x)<-paste0("G",1:6)
ann<-data.frame(cell_id=colnames(x),group=c("M","M","B","B","M","B"),coarse_group=c("Malignant_total","Malignant_total","B","B","Malignant_total","B"))
donor<-c("D1","D2","D1","D2","D3","D3")
ref<-tall_build_reference(x,ann,donor,"SYNTHETIC_RELEASE_EXAMPLE_V1")
bulk<-cbind(V1=rowSums(x[,c(1,3),drop=FALSE]),V2=rowSums(x[,c(2,4),drop=FALSE]))
cfg<-list(iterations=120L,burnin=40L,thin=4L)
# Short runs exercise software only; not inferential convergence or accuracy.
r<-tall_deconv(bulk,ref,config=cfg,out_dir="example_no_flow")
f<-data.frame(sample_id="V1",group="Malignant_total",kind="lower",lower=.4,measurement_error=.05,denominator_scope="modeled_nucleated",original_denominator="synthetic known parent",gate_identity="synthetic malignant core")
on<-tall_add_flow(r,f,out_dir="example_with_flow")
off<-tall_deconv(bulk,ref,flow=f,config=c(cfg,list(flow_strength=0)),out_dir="example_flow_disabled")
truth<-list(counts=x,cell_annotations=ann,patient_ids=c("V1","V2","V1","V2","V1","V2"))
bench<-tall_benchmark(bulk,truth,ref,split="independent",min_cells=1L,config=cfg,out_dir="example_paired_validation")
stopifnot(all(tall_qc(r)$pass),all(tall_qc(on)$pass),all(on$flow$used),!any(off$flow$used))
stopifnot(nrow(tall_extract(r,"composition_rna"))==2)
stopifnot(all(tall_verify(r$path)$pass))

test_that("native kernel reproduces the exported upstream sampler", {
  phi<-matrix(c(.8,.2,.2,.8),2);keep<-seq(52L,300L,2L)
  set.seed(123);a<-BayesPrism::sample.Z.theta_n(c(7,13),phi,.1,keep,FALSE)
  set.seed(123);b<-TALLBMDeconv:::tbm_bp_initial(c(7,13),phi,.1,keep)
  expect_equal(a$theta_n,b$theta_n,tolerance=1e-10);expect_equal(a$Z_n,b$Z_n,tolerance=1e-10)
  set.seed(123);c<-TALLBMDeconv:::tbm_flow_sample(c(7,13),phi,.1,keep,c(4,1),matrix(c(1,0),1),.7,.7,.03,0)
  expect_identical(b$theta_trace,c$theta_trace)
})
test_that("Rhat uses within-chain variance separately for every component", {
  a<-matrix(c(1:8,seq(10,80,10),seq(2,16,2)),ncol=3)
  b<-a+matrix(c(rep(.2,8),rep(3,8),rep(1,8)),ncol=3)
  within<-(apply(a,2,stats::var)+apply(b,2,stats::var))/2
  between<-apply(rbind(colMeans(a),colMeans(b)),2,stats::var)
  expected<-sqrt(((nrow(a)-1)/nrow(a)*within+between)/within)
  expect_equal(TALLBMDeconv:::.rhat(list(a,b)),expected)
})
test_that("end to end outputs conserve RNA, match order and are deterministic", {
  f<-fixture();a<-tall_deconv(f$bulk,f$ref,config=f$cfg);b<-tall_deconv(f$bulk,f$ref,config=f$cfg)
  expect_equal(tall_extract(a),tall_extract(b),tolerance=0)

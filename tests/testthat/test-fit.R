})
test_that("typed observations enter inference and unknown is not zero", {
  f<-fixture();unknown<-flow_fixture(kind="unknown",value=NA_real_)
  a<-tall_deconv(f$bulk,f$ref,config=f$cfg);b<-tall_add_flow(a,unknown)
  expect_equal(tall_extract(a),tall_extract(b),tolerance=0)
  point<-flow_fixture(value=.85);c<-tall_add_flow(a,point)
  expect_false(isTRUE(all.equal(tall_extract(a),tall_extract(c))))
  expect_true(all(tall_verify(c$path)$pass))
  zero<-flow_fixture(value=0);expect_equal(TALLBMDeconv:::.prepare_flow(zero,f$ref,colnames(f$bulk))$effective_lower,0)
  lower<-flow_fixture(kind="lower");q<-TALLBMDeconv:::.prepare_flow(lower,f$ref,colnames(f$bulk));expect_equal(q$effective_upper,1)
  interval<-flow_fixture(kind="interval");q<-TALLBMDeconv:::.prepare_flow(interval,f$ref,colnames(f$bulk));expect_equal(q$effective_upper,.8)
  point$denominator_scope<-"lymphocyte_gate";expect_error(tall_add_flow(a,point),"denominator")
  point$sample_id<-"missing";expect_error(tall_add_flow(a,point),"sample ID")
})
test_that("zero allocated expression is undefined, never fabricated", {
  phi<-matrix(c(1,0,0,1),2,dimnames=list(c("A","B"),c("g1","g2")))
  set.seed(1);z<-TALLBMDeconv:::tbm_bp_initial(c(10,0),phi,1e-8,seq(20L,100L,10L))$Z_n
  expect_equal(sum(z[,2]),0)
  x<-matrix(c(10,0,0,10),2,dimnames=list(c("g1","g2"),c("c1","c2")))
  ref<-tall_build_reference(x,data.frame(cell_id=colnames(x),group=c("A","B")),c("D","D"))
  bulk<-matrix(c(10,0),2,1,dimnames=list(rownames(x),"V"))
  result<-tall_deconv(bulk,ref,config=list(iterations=100L,burnin=20L,thin=4L))
  expect_true(all(is.na(tall_extract(result,"expression","B"))))
  expect_true(all(tall_extract(result,"contribution_cpm","B")==0))
  expect_true(all(tall_qc(result)$pass))
})
test_that("typed flow sampler matches independent numerical point/lower oracles", {
  phi<-matrix(.5,2,2);keep<-seq(2002L,40000L,2L);G<-matrix(c(1,0),1)
  set.seed(482);point<-TALLBMDeconv:::tbm_flow_sample(c(1,1),phi,1,keep,c(4,1),G,.7,.7,.05,2)
  set.seed(483);lower<-TALLBMDeconv:::tbm_flow_sample(c(1,1),phi,1,keep,c(4,1),G,.7,1,.05,2)
  v<-seq(.00001,.99999,length.out=100000);p<-(v/4)/(v/4+1-v);h<-function(z)ifelse(z<=1,.5*z*z,z-.5)
  lp<-exp(-2*h(abs(p-.7)/.05));ll<-exp(-2*h(pmax(.7-p,0)/.05))
  expect_lt(abs(point$theta_n[1]-sum(v*lp)/sum(lp)),.02)
  expect_lt(abs(lower$theta_n[1]-sum(v*ll)/sum(ll)),.02)
  expect_gt(lower$theta_n[1],point$theta_n[1])
})
